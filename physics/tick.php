function physicsLoadObjects(PDO $pdo): array
{
    $rows = $pdo->query(
        "SELECT *
         FROM live_objects
         ORDER BY id
         FOR UPDATE"
    )->fetchAll();

    $objects = [];

    foreach ($rows as $row) {
        $id = (int)$row['id'];

        $objects[$id] = [
            'id' => $id,
            'parent_object_id' => $row['parent_object_id'] !== null
                ? (int)$row['parent_object_id']
                : null,
            'is_attached' => (bool)$row['is_attached'],
            'dry_mass_kg' => (float)$row['dry_mass_kg'],
            'radius_m' => $row['radius_m'] !== null ? (float)$row['radius_m'] : 0.0,

            'x_m' => ((float)$row['x_cm'] + (float)$row['x_subcm']) / 100.0,
            'y_m' => ((float)$row['y_cm'] + (float)$row['y_subcm']) / 100.0,
            'z_m' => ((float)$row['z_cm'] + (float)$row['z_subcm']) / 100.0,

            'vx_m_s' => (float)$row['vx_cm_s'] / 100.0,
            'vy_m_s' => (float)$row['vy_cm_s'] / 100.0,
            'vz_m_s' => (float)$row['vz_cm_s'] / 100.0,

            'pitch_deg' => $row['pitch_deg'] !== null ? (float)$row['pitch_deg'] : null,
            'yaw_deg' => $row['yaw_deg'] !== null ? (float)$row['yaw_deg'] : null,
            'roll_deg' => $row['roll_deg'] !== null ? (float)$row['roll_deg'] : null,

            'pitch_rate_deg_s' => $row['pitch_rate_deg_s'] !== null
                ? (float)$row['pitch_rate_deg_s']
                : null,
            'yaw_rate_deg_s' => $row['yaw_rate_deg_s'] !== null
                ? (float)$row['yaw_rate_deg_s']
                : null,
            'roll_rate_deg_s' => $row['roll_rate_deg_s'] !== null
                ? (float)$row['roll_rate_deg_s']
                : null,

            'produces_gravity' => (bool)$row['produces_gravity'],
            'affected_by_gravity' => (bool)$row['affected_by_gravity'],
            'surface_locked' => (bool)$row['surface_locked'],
        ];
    }

    return $objects;
}

function physicsObjectMasses(PDO $pdo, array $objects): array
{
    $fuel = [];

    foreach ($pdo->query(
        "SELECT live_object_id, COALESCE(SUM(remaining_kg),0) AS fuel_mass
         FROM live_fuel_tanks
         GROUP BY live_object_id"
    )->fetchAll() as $row) {
        $fuel[(int)$row['live_object_id']] = (float)$row['fuel_mass'];
    }

    $masses = [];
    foreach ($objects as $id => $object) {
        /*
         * Definition dry mass is the complete dry object mass.
         * Engine definition mass is metadata and is not added again,
         * avoiding double-counting published stage dry masses.
         */
        $masses[$id] = $object['dry_mass_kg'] + ($fuel[$id] ?? 0.0);
    }

    return $masses;
}

function physicsStackMasses(array $rootMembers, array $objectMasses): array
{
    $stackMasses = [];

    foreach ($rootMembers as $rootId => $memberIds) {
        $stackMasses[$rootId] = 0.0;
        foreach ($memberIds as $memberId) {
            $stackMasses[$rootId] += $objectMasses[$memberId] ?? 0.0;
        }
    }

    return $stackMasses;
}

function physicsCombineAcceleration(array $a, array $b): array
{
    $out = [];

    foreach ($a as $rootId => $vector) {
        $out[$rootId] = [
            'x' => $vector['x'] + ($b[$rootId]['x'] ?? 0.0),
            'y' => $vector['y'] + ($b[$rootId]['y'] ?? 0.0),
            'z' => $vector['z'] + ($b[$rootId]['z'] ?? 0.0),
        ];
    }

    foreach ($b as $rootId => $vector) {
        if (!isset($out[$rootId])) {
            $out[$rootId] = $vector;
        }
    }

    return $out;
}

function physicsWrapDegrees(?float $value): ?float
{
    if ($value === null) {
        return null;
    }

    $value = fmod($value + 180.0, 360.0);
    if ($value < 0.0) {
        $value += 360.0;
    }

    return $value - 180.0;
}

function physicsIntegrateOrientation(array &$object, float $dt): void
{
    if ($object['pitch_deg'] !== null && $object['pitch_rate_deg_s'] !== null) {
        $object['pitch_deg'] = physicsWrapDegrees(
            $object['pitch_deg'] + $object['pitch_rate_deg_s'] * $dt
        );
    }

    if ($object['yaw_deg'] !== null && $object['yaw_rate_deg_s'] !== null) {
        $object['yaw_deg'] = physicsWrapDegrees(
            $object['yaw_deg'] + $object['yaw_rate_deg_s'] * $dt
        );
    }

    if ($object['roll_deg'] !== null && $object['roll_rate_deg_s'] !== null) {
        $object['roll_deg'] = physicsWrapDegrees(
            $object['roll_deg'] + $object['roll_rate_deg_s'] * $dt
        );
    }
}

function physicsSplitCentimeters(float $meters): array
{
    $centimeters = $meters * 100.0;

    if (!is_finite($centimeters)) {
        throw new RuntimeException('Non-finite position generated by physics.');
    }

    $whole = floor($centimeters);

    if ($whole < PHP_INT_MIN || $whole > PHP_INT_MAX) {
        throw new RuntimeException('Position exceeded signed BIGINT/PHP integer range.');
    }

    return [(int)$whole, $centimeters - $whole];
}

function physicsPersistObjects(PDO $pdo, array $objects): void
{
    $stmt = $pdo->prepare(
        "UPDATE live_objects SET
            x_cm=:x_cm, x_subcm=:x_sub,
            y_cm=:y_cm, y_subcm=:y_sub,
            z_cm=:z_cm, z_subcm=:z_sub,
            vx_cm_s=:vx, vy_cm_s=:vy, vz_cm_s=:vz,
            pitch_deg=:pitch, yaw_deg=:yaw, roll_deg=:roll
         WHERE id=:id"
    );

    foreach ($objects as $id => $object) {
        [$xCm,$xSub] = physicsSplitCentimeters($object['x_m']);
        [$yCm,$ySub] = physicsSplitCentimeters($object['y_m']);
        [$zCm,$zSub] = physicsSplitCentimeters($object['z_m']);

        $stmt->execute([
            'x_cm' => $xCm,
            'x_sub' => number_format($xSub, 9, '.', ''),
            'y_cm' => $yCm,
            'y_sub' => number_format($ySub, 9, '.', ''),
            'z_cm' => $zCm,
            'z_sub' => number_format($zSub, 9, '.', ''),
            'vx' => number_format($object['vx_m_s'] * 100.0, 9, '.', ''),
            'vy' => number_format($object['vy_m_s'] * 100.0, 9, '.', ''),
            'vz' => number_format($object['vz_m_s'] * 100.0, 9, '.', ''),
            'pitch' => $object['pitch_deg'] !== null
                ? number_format($object['pitch_deg'], 4, '.', '')
                : null,
            'yaw' => $object['yaw_deg'] !== null
                ? number_format($object['yaw_deg'], 4, '.', '')
                : null,
            'roll' => $object['roll_deg'] !== null
                ? number_format($object['roll_deg'], 4, '.', '')
                : null,
            'id' => $id,
        ]);
    }
}

/**
 * Advance the universe toward real database time.
 *
 * Returns processed seconds. A maximum catch-up slice keeps one request
 * bounded; repeated cron-loop calls continue catching up until current.
 */
function physicsAdvance(PDO $pdo, float $maxCatchupSeconds = 300.0): float
{
    $lock = (int)$pdo->query(
        "SELECT GET_LOCK('moon_program_physics_tick', 0)"
    )->fetchColumn();

    if ($lock !== 1) {
        return 0.0;
    }

    try {
        $pdo->beginTransaction();

        $state = $pdo->query(
            "SELECT *
             FROM simulation_state
             WHERE id=1
             FOR UPDATE"
        )->fetch();

        if (!$state || !(bool)$state['physics_enabled']) {
            $pdo->commit();
            return 0.0;
        }

        $nowString = (string)$pdo->query("SELECT NOW(6)")->fetchColumn();

        $last = new DateTimeImmutable((string)$state['last_tick_at']);
        $now = new DateTimeImmutable($nowString);

        $elapsed =
            (float)$now->format('U.u')
            - (float)$last->format('U.u');

        if ($elapsed <= 0.000001) {
            $pdo->commit();
            return 0.0;
        }

        $toProcess = min($elapsed, $maxCatchupSeconds);
        $nominal = max(0.01, min(1.0, (float)$state['nominal_tick_seconds']));

        $objects = physicsLoadObjects($pdo);

        if (!$objects) {
            $processedMicros = (int)round($toProcess * 1000000.0);
            $newLast = $last
                ->modify('+' . $processedMicros . ' microseconds')
                ->format('Y-m-d H:i:s.u');

            $stmt = $pdo->prepare(
                "UPDATE simulation_state SET last_tick_at=:last WHERE id=1"
            );
            $stmt->execute(['last' => $newLast]);

            $pdo->commit();
            return $toProcess;
        }

        $remaining = $toProcess;

        while ($remaining > 0.0000005) {
            $dt = min($nominal, $remaining);

            $rootMembers = physicsRootMembers($objects);
            $objectMasses = physicsObjectMasses($pdo, $objects);
            $stackMasses = physicsStackMasses($rootMembers, $objectMasses);

            $gravityStart = physicsGravity(
                $objects,
                $rootMembers,
                $stackMasses
            );

            /*
             * Propulsion consumes exactly dt worth of propellant here and
             * returns the acceleration produced during this substep.
             */
            $propulsion = physicsPropulsion(
                $pdo,
                $dt,
                $objects,
                $rootMembers,
                $stackMasses
            );

            $accelStart = physicsCombineAcceleration(
                $gravityStart,
                $propulsion
            );

            // Kick half-step, drift full-step.
            foreach ($rootMembers as $rootId => $_members) {
                if ($objects[$rootId]['surface_locked']) {
                    continue;
                }

                $a = $accelStart[$rootId] ?? ['x'=>0.0,'y'=>0.0,'z'=>0.0];

                $objects[$rootId]['vx_m_s'] += 0.5 * $a['x'] * $dt;
                $objects[$rootId]['vy_m_s'] += 0.5 * $a['y'] * $dt;
                $objects[$rootId]['vz_m_s'] += 0.5 * $a['z'] * $dt;

                $objects[$rootId]['x_m'] += $objects[$rootId]['vx_m_s'] * $dt;
                $objects[$rootId]['y_m'] += $objects[$rootId]['vy_m_s'] * $dt;
                $objects[$rootId]['z_m'] += $objects[$rootId]['vz_m_s'] * $dt;

                physicsIntegrateOrientation($objects[$rootId], $dt);
            }

            physicsSynchronizeAttachments($objects, $rootMembers);

            // Gravity is re-evaluated at the new positions for leapfrog.
            $objectMassesEnd = physicsObjectMasses($pdo, $objects);
            $stackMassesEnd = physicsStackMasses(
                $rootMembers,
                $objectMassesEnd
            );

            $gravityEnd = physicsGravity(
                $objects,
                $rootMembers,
                $stackMassesEnd
            );

            $accelEnd = physicsCombineAcceleration(
                $gravityEnd,
                $propulsion
            );

            // Final half-kick.
            foreach ($rootMembers as $rootId => $_members) {
                if ($objects[$rootId]['surface_locked']) {
                    continue;
                }

                $a = $accelEnd[$rootId] ?? ['x'=>0.0,'y'=>0.0,'z'=>0.0];

                $objects[$rootId]['vx_m_s'] += 0.5 * $a['x'] * $dt;
                $objects[$rootId]['vy_m_s'] += 0.5 * $a['y'] * $dt;
                $objects[$rootId]['vz_m_s'] += 0.5 * $a['z'] * $dt;
            }

            physicsSynchronizeAttachments($objects, $rootMembers);
            $remaining -= $dt;
        }

        physicsPersistObjects($pdo, $objects);

        $finalRootMembers = physicsRootMembers($objects);
        $finalMasses = physicsObjectMasses($pdo, $objects);
        $finalStackMasses = physicsStackMasses(
            $finalRootMembers,
            $finalMasses
        );

        $processedMicros = (int)round($toProcess * 1000000.0);
        $newLastObject = $last->modify(
            '+' . $processedMicros . ' microseconds'
        );
        $newLast = $newLastObject->format('Y-m-d H:i:s.u');

        $stateUpdate = $pdo->prepare(
            "UPDATE simulation_state
             SET last_tick_at=:last
             WHERE id=1"
        );
        $stateUpdate->execute(['last' => $newLast]);

        physicsRecordTelemetry(
            $pdo,
            $objects,
            $finalRootMembers,
            $finalStackMasses,
            $newLast
        );

        $pdo->commit();
        return $toProcess;
    } catch (Throwable $e) {
        if ($pdo->inTransaction()) {
            $pdo->rollBack();
        }
        throw $e;
    } finally {
        try {
            $pdo->query("SELECT RELEASE_LOCK('moon_program_physics_tick')");
        } catch (Throwable $ignored) {
        }
    }
}
